"""Embed the Phase 3 source helper so 03 remains a standalone script."""
import argparse
from pathlib import Path

BEGIN = '# BEGIN ATLAS ADDON SOURCES (generated by scripts/sync-addon-sources.py)'
END = '# END ATLAS ADDON SOURCES'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    path = root / '03-install-addons.sh'
    source = path.read_text()
    helper = (root / 'scripts/addons/sources.py').read_text()
    payload = BEGIN + '\nwrite_source_helper() {\n  cat > "$TMP_DIR/addon-sources.py" <<\'ATLAS_ADDON_SOURCES_PY\'\n' + helper + 'ATLAS_ADDON_SOURCES_PY\n}\n' + END
    before, remainder = source.split(BEGIN, 1)
    _, after = remainder.split(END, 1)
    expected = before + payload + after
    if source != expected:
        if args.check:
            print('Add-on source payload is out of date; run python3 scripts/sync-addon-sources.py')
            return 1
        path.write_text(expected)
    print('Standalone add-on source payload is current')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
