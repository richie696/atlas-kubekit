#!/usr/bin/env python3
"""Keep Phase 1 standalone by embedding the canonical storage helper."""
import argparse
from pathlib import Path

BEGIN = '# BEGIN ATLAS KUBEKIT STORAGE (generated by scripts/sync-storage.py)'
END = '# END ATLAS KUBEKIT STORAGE'


def content(root):
    helper = (root / 'scripts/stages/storage.py').read_text()
    # Keep stdin attached to the terminal: selection reads answers from it.
    return BEGIN + '\nstorage_tool() {\n  local storage_source\n  IFS= read -r -d \'\' storage_source <<\'ATLAS_STORAGE_PY\' || true\n' + helper + 'ATLAS_STORAGE_PY\n  ATLAS_LOCALES_DIR="$SCRIPT_DIR/locales" ATLAS_LANG="${ATLAS_LANG:-en}" python3 -c "$storage_source" "$@"\n}\n' + END


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    path = root / '01-prepare-node.sh'
    source = path.read_text()
    if BEGIN in source:
        before, remainder = source.split(BEGIN, 1)
        _, after = remainder.split(END, 1)
    else:
        before, after = source.split('valid_ip() {', 1)
        after = '\nvalid_ip() {' + after
    expected = before + content(root) + after
    if source != expected:
        if args.check:
            print('Storage payload is out of date; run python3 scripts/sync-storage.py')
            return 1
        path.write_text(expected)
    print('Standalone storage payload is current')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
